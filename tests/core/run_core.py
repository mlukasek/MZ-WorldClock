"""Test the portable time library (src/core/wctime.c) on the Z80 against Python's zoneinfo.

    python tests/core/run_core.py [--cc sccz80|sdcc] [--random N]

Generates test vectors (around every DST transition 2008-2099 of the tested zones, plus random times),
compiles tests/core/test_wctime.c for the z88dk +test target, runs it in z88dk-ticks and compares every
line with the expected one. Needs z88dk (Z88DK, default E:\\SHARP_GIT\\Tools\\z88dk-nightly) and, on Windows,
the tzdata package for zoneinfo (python -m pip install --user tzdata).
"""
import argparse
import os
import random
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from zoneinfo import ZoneInfo

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
Z88DK = os.environ.get('Z88DK', r'E:\SHARP_GIT\Tools\z88dk-nightly')
EPOCH = datetime(2000, 1, 1, tzinfo=timezone.utc)

# (tz name, standard offset in minutes, rule, first year the current rule holds)
ZONES = [('Europe/Paris', 60, 'EU', 2000), ('Europe/London', 0, 'EU', 2000), ('Europe/Prague', 60, 'EU', 2000),
         ('America/Los_Angeles', -480, 'US', 2008), ('America/New_York', -300, 'US', 2008),
         ('Australia/Sydney', 600, 'AU', 2009), ('Asia/Tokyo', 540, 'NONE', 2000),
         ('Europe/Moscow', 180, 'NONE', 2015), ('America/Sao_Paulo', -180, 'NONE', 2020),
         ('Africa/Johannesburg', 120, 'NONE', 2000), ('Asia/Shanghai', 480, 'NONE', 2000)]
LAST_YEAR = 2099


def secs(dt):
    return int((dt - EPOCH).total_seconds())


def offset_min(tz, utc_s):
    return int((EPOCH + timedelta(seconds=utc_s)).astimezone(tz).utcoffset().total_seconds()) // 60


def transitions(tz, y0, y1):
    """UTC seconds of the offset changes in years y0..y1 (by day scan, then bisection to the second)."""
    out = []
    t = secs(datetime(y0, 1, 1, tzinfo=timezone.utc))
    end = secs(datetime(y1 + 1, 1, 1, tzinfo=timezone.utc))
    prev = offset_min(tz, t)
    while t < end:
        n = t + 86400
        o = offset_min(tz, n)
        if o != prev:
            lo, hi = t, n
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if offset_min(tz, mid) == prev:
                    lo = mid
                else:
                    hi = mid
            out.append(hi)
            prev = o
        t = n
    return out


def expected(tz, std, utc_s):
    off = offset_min(tz, utc_s)
    local_s = utc_s + off * 60
    local = EPOCH.replace(tzinfo=None) + timedelta(seconds=local_s)
    wday = (local.weekday() + 1) % 7                     # 0 = Sunday
    # local -> UTC as wctime: of the instants showing this local time take the DST one (the earlier, in the
    # repeated hour); if there is none (the skipped hour), standard time
    valid = [o for o in (std + 60, std) if offset_min(tz, local_s - o * 60) == o]
    back = local_s - (valid[0] if valid else std) * 60
    return '%04X %s%d %08X' % (off & 0xFFFF, local.strftime('%Y%m%d%H%M%S'), wday, back & 0xFFFFFFFF)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cc', default='sccz80')
    ap.add_argument('--random', type=int, default=300)
    a = ap.parse_args()
    random.seed(1)
    vectors = []
    for zi, (name, std, rule, y0) in enumerate(ZONES):
        tz = ZoneInfo(name)
        for t in transitions(tz, y0, LAST_YEAR):
            for d in (-3601, -3600, -1, 0, 1, 3599, 3600):
                vectors.append((t + d, zi))
        lo = secs(datetime(y0, 1, 2, tzinfo=timezone.utc))
        hi = secs(datetime(LAST_YEAR, 12, 30, tzinfo=timezone.utc))
        vectors += [(random.randrange(lo, hi), zi) for _ in range(a.random // len(ZONES) + 1)]
    exp = [expected(ZoneInfo(ZONES[z][0]), ZONES[z][1], t) for t, z in vectors]

    bdir = os.path.join(ROOT, 'build', 'test')
    os.makedirs(bdir, exist_ok=True)
    with open(os.path.join(bdir, 'vectors.h'), 'w', newline='\n') as f:
        f.write('/* Generated by tests/core/run_core.py - do not edit. */\n')
        f.write('struct test_zone { int16_t std; uint8_t rule; };\n')
        f.write('static const struct test_zone ZONES[] = {\n')
        for name, std, rule, _ in ZONES:
            f.write('    {%d, DST_%s},   /* %s */\n' % (std, rule, name))
        f.write('};\nstruct test_vector { uint32_t utc; uint8_t zone; };\n')
        f.write('#define N_VECTORS %d\nstatic const struct test_vector VECTORS[N_VECTORS] = {\n' % len(vectors))
        for t, z in vectors:
            f.write('    {%dUL, %d},\n' % (t, z))
        f.write('};\n')

    env = dict(os.environ, ZCCCFG=os.path.join(Z88DK, 'lib', 'config'),
               PATH=os.path.join(Z88DK, 'bin') + os.pathsep + os.environ['PATH'])
    out_bin = os.path.join(bdir, 'test_wctime-%s.bin' % a.cc)
    cmd = ['zcc', '+test', '-O2', '-I' + bdir, '-o', out_bin, os.path.join(ROOT, 'tests', 'core', 'test_wctime.c'),
           os.path.join(ROOT, 'src', 'core', 'wctime.c')]
    if a.cc == 'sdcc':
        cmd.insert(2, '-compiler=sdcc')
    r = subprocess.run(cmd, env=env, capture_output=True, text=True, shell=(os.name == 'nt'))
    if r.returncode:
        print(r.stdout + r.stderr)
        sys.exit(1)
    r = subprocess.run([os.path.join(Z88DK, 'bin', 'z88dk-ticks'), '-counter', '4000000000', out_bin],
                       env=env, capture_output=True, text=True)
    got = [l for l in r.stdout.splitlines() if re.match(r'^[0-9A-F]{4} ', l)]
    other = [l for l in r.stdout.splitlines() if not re.match(r'^[0-9A-F]{4} ', l)]
    bad = 0
    for i, (e, g) in enumerate(zip(exp, got)):
        if e != g:
            bad += 1
            if bad <= 10:
                t, z = vectors[i]
                print('MISMATCH %s utc=%d (%s): expected %s got %s' % (ZONES[z][0], t,
                      (EPOCH + timedelta(seconds=t)).isoformat(), e, g))
    if len(got) != len(exp):
        print('expected %d lines, got %d' % (len(exp), len(got)))
        bad += 1
    print('%s: %d vectors, %d mismatches, binary %d bytes; ticks: %s'
          % (a.cc, len(exp), bad, os.path.getsize(out_bin), ' '.join(other[-2:])))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
