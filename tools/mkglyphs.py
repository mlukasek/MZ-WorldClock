"""Own glyphs: data/glyphs.txt -> build/gen/glyphs.c, glyphs.h (and a PNG preview). Standard library only.

    python tools/mkglyphs.py data/glyphs.txt build/gen
    python tools/mkglyphs.py data/glyphs.txt --png work/glyphs.png

In the C table a row byte has the leftmost pixel in bit 0, as in the Sharp character generators.
"""
import argparse
import os
import re
import sys


def parse(path):
    glyphs = []
    cur = None
    for n, raw in enumerate(open(path, encoding='utf-8'), 1):
        line = raw.rstrip('\n').strip()
        if not line or line.startswith('#') and not re.fullmatch(r'[#.]{8}', line):
            continue
        m = re.fullmatch(r'\[(\w+) ([01]) ([0-9A-Fa-f]{2})\]', line)
        if m:
            cur = {'name': m.group(1), 'set': int(m.group(2)), 'code': int(m.group(3), 16), 'rows': []}
            glyphs.append(cur)
            continue
        if not re.fullmatch(r'[#.]{8}', line) or cur is None or len(cur['rows']) == 8:
            raise SystemExit('%s:%d: expected a glyph header or 8 pixels' % (path, n))
        cur['rows'].append(sum(1 << i for i, c in enumerate(line) if c == '#'))
    for g in glyphs:
        if len(g['rows']) != 8:
            raise SystemExit('%s: glyph %s has %d rows' % (path, g['name'], len(g['rows'])))
    return glyphs


def write_c(glyphs, outdir, src):
    os.makedirs(outdir, exist_ok=True)
    gen = '/* Generated by tools/mkglyphs.py from %s - do not edit. */\n' % src.replace('\\', '/')
    h = [gen, '#ifndef WC_GLYPHS_H', '#define WC_GLYPHS_H', '', '#include <stdint.h>', '',
         'struct glyph {', '    uint8_t set;           /* character set 0 / 1 (attribute bit 7) */',
         '    uint8_t code;          /* display code */', '    uint8_t rows[8];       /* bit 0 = the leftmost pixel */',
         '};', '', '#define GLYPHS %d' % len(glyphs), 'extern const struct glyph glyphs[GLYPHS];', '']
    h += ['#define GLYPH_%s %d' % (g['name'], i) for i, g in enumerate(glyphs)]
    h += ['', '#endif', '']
    c = [gen, '#include "glyphs.h"', '', 'const struct glyph glyphs[GLYPHS] = {']
    for g in glyphs:
        c.append('    {%d, 0x%02X, {%s}},   /* %s */' % (g['set'], g['code'], ', '.join('0x%02X' % r for r in g['rows']),
                                                       g['name']))
    c += ['};', '']
    with open(os.path.join(outdir, 'glyphs.h'), 'w', newline='\n') as f:
        f.write('\n'.join(h))
    with open(os.path.join(outdir, 'glyphs.c'), 'w', newline='\n') as f:
        f.write('\n'.join(c))


def write_png(glyphs, path, scale=6):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import cgrom
    w = len(glyphs) * (8 * scale + 4) + 4
    h = 8 * scale + 8
    rows = [bytearray(b'\x40\x40\x40' * w) for _ in range(h)]
    for k, g in enumerate(glyphs):
        for y in range(8):
            for x in range(8):
                col = b'\xff\xff\xff' if (g['rows'][y] >> x) & 1 else b'\x00\x00\x00'
                for sy in range(scale):
                    o = (4 + k * (8 * scale + 4) + x * scale) * 3
                    rows[4 + y * scale + sy][o:o + 3 * scale] = col * scale
    cgrom.write_png(path, w, h, rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src')
    ap.add_argument('outdir', nargs='?')
    ap.add_argument('--png')
    a = ap.parse_args()
    glyphs = parse(a.src)
    if a.outdir:
        write_c(glyphs, a.outdir, a.src)
    if a.png:
        write_png(glyphs, a.png)


if __name__ == '__main__':
    main()
